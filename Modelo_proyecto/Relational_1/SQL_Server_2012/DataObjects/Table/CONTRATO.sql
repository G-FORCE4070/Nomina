CREATE TABLE CONTRATO 
    (
     ID_CONTRATO NUMERIC (10) NOT NULL , 
     FECHA_INICIO DATE , 
     TIPO_CONTRATO VARCHAR (30) , 
     PERSONA_CEDULA NUMERIC (10) NOT NULL , 
     NOMINA_ID_NOMINA NUMERIC (10) NOT NULL , 
     PRESTACION_SOCIAL_ID_PRESTACION NUMERIC (10) NOT NULL , 
     LIQUIDACION_DEFINITIVA_ID_LIQUIDACION NUMERIC (10) NOT NULL , 
     ESTADO VARCHAR (10) NOT NULL 
    )
GO 

    


CREATE UNIQUE NONCLUSTERED INDEX 
    CONTRATO__IDX ON CONTRATO 
    ( 
     LIQUIDACION_DEFINITIVA_ID_LIQUIDACION 
    ) 
GO 


CREATE UNIQUE NONCLUSTERED INDEX 
    CONTRATO__IDXv1 ON CONTRATO 
    ( 
     NOMINA_ID_NOMINA 
    ) 
GO 


CREATE UNIQUE NONCLUSTERED INDEX 
    CONTRATO__IDXv2 ON CONTRATO 
    ( 
     PRESTACION_SOCIAL_ID_PRESTACION 
    ) 
GO