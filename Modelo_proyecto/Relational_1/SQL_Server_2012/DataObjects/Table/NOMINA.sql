CREATE TABLE NOMINA 
    (
     ID_NOMINA NUMERIC (10) NOT NULL , 
     SALARIO_BASE NUMERIC (20) , 
     CONTRATO_ID_CONTRATO NUMERIC (10) NOT NULL , 
