CREATE TABLE ARL (
  NIT_ARL BIGINT NOT NULL,
  NOMBRE_ARL VARCHAR(15),
  NUMERO_CONTACTO BIGINT,
  PRIMARY KEY (NIT_ARL)
);

CREATE TABLE BONIFICACION (
  ID_BONIFICACION INT NOT NULL AUTO_INCREMENT,
  VALOR BIGINT,
  TIPO_BONIFICACION VARCHAR(40),
  PRIMARY KEY (ID_BONIFICACION)
);

CREATE TABLE BONIFICACION_NOMINA (
  NOMINA_ID_NOMINA INT NOT NULL,
  BONIFICACION_ID_BONIFICACION INT NOT NULL,
  PRIMARY KEY (NOMINA_ID_NOMINA, BONIFICACION_ID_BONIFICACION)
);

CREATE TABLE CAJA_COMPENSACION (
  NIT_CAJA BIGINT NOT NULL,
  NOMBRE_CAJA VARCHAR(20),
  PRIMARY KEY (NIT_CAJA)
);

CREATE TABLE CONTRATO (
  ID_CONTRATO INT NOT NULL AUTO_INCREMENT,
  FECHA_INICIO DATE,
  TIPO_CONTRATO VARCHAR(30),
  LIQUIDACION_DEFINITIVA_ID_LIQUIDACION INT NOT NULL,
  FECHA_TERMINACION DATE,
  ESTADO VARCHAR(10) NOT NULL,
  PERSONA_ID_PERSONA INT NOT NULL,
  PRIMARY KEY (ID_CONTRATO),
  UNIQUE KEY CONTRATO_IDX_LIQ (LIQUIDACION_DEFINITIVA_ID_LIQUIDACION)
);

CREATE TABLE DEDUCCION (
  ID_DEDUCCION INT NOT NULL AUTO_INCREMENT,
  TIPO_DEDUCCION VARCHAR(40) NOT NULL,
  VALOR BIGINT,
  RAZON VARCHAR(150),
  PRIMARY KEY (ID_DEDUCCION)
);

CREATE TABLE DEDUCCION_NOMINA (
  NOMINA_ID_NOMINA INT NOT NULL,
  DEDUCCION_ID_DEDUCCION INT NOT NULL,
  PRIMARY KEY (NOMINA_ID_NOMINA, DEDUCCION_ID_DEDUCCION)
);

CREATE TABLE DEPARTAMENTO (
  ID_DEPARTAMENTO INT NOT NULL AUTO_INCREMENT,
  NOMBRE_DEPARTAMENTO VARCHAR(20),
  PRIMARY KEY (ID_DEPARTAMENTO)
);

CREATE TABLE EPS (
  NIT_EPS BIGINT NOT NULL,
  NOMBRE_EPS VARCHAR(20),
  PRIMARY KEY (NIT_EPS)
);

CREATE TABLE LIQUIDACION_DEFINITIVA (
  ID_LIQUIDACION INT NOT NULL AUTO_INCREMENT,
  VALOR_INDEMNIZACION BIGINT,
  FECHA_LIQUIDACION DATE,
  VACACIONES_PENDIENTES INT,
  PRIMA_PROPORCIONAL BIGINT,
  SALARIO_PENDIENTE BIGINT,
  TOTAL_LIQUIDACION BIGINT,
  PRIMARY KEY (ID_LIQUIDACION)
);

CREATE TABLE NOMINA (
  ID_NOMINA INT NOT NULL AUTO_INCREMENT,
  SALARIO_BASE BIGINT,
  FECHA_PAGO DATE,
  SALARIO_NETO BIGINT,
  CONTRATO_ID_CONTRATO INT NOT NULL,
  PRIMARY KEY (ID_NOMINA)
);

CREATE TABLE PENSION (
  NIT_PENSION BIGINT NOT NULL,
  NOMBRE_FONDO VARCHAR(20),
  PRIMARY KEY (NIT_PENSION)
);

CREATE TABLE PERSONA (
  CEDULA BIGINT NOT NULL,
  APELLIDO VARCHAR(20),
  NOMBRE VARCHAR(20),
  FECHA_NACIMIENTO DATE,
  DIRECCION VARCHAR(30),
  CONTACTO BIGINT,
  DEPARTAMENTO_ID_DEPARTAMENTO INT NOT NULL,
  CARGO VARCHAR(40) NOT NULL,
  ID_PERSONA INT NOT NULL AUTO_INCREMENT,
  PRIMARY KEY (ID_PERSONA)
);

CREATE TABLE PRESTACION_SOCIAL (
  ID_PRESTACION INT NOT NULL AUTO_INCREMENT,
  VALOR_CESANTIA BIGINT,
  INTERES BIGINT,
  VALOR_PRIMA BIGINT,
  DIAS_VACACIONES INT,
  FECHA_LIQUIDACION DATE,
  CONTRATO_ID_CONTRATO INT NOT NULL,
  PRIMARY KEY (ID_PRESTACION)
);

CREATE TABLE SEGURIDAD_SOCIAL (
  FECHA_PAGO DATE,
  SEGURIDAD_SOCIAL_ID BIGINT NOT NULL AUTO_INCREMENT,
  PERSONA_ID_PERSONA INT NOT NULL,
  ARL_NIT_ARL BIGINT NOT NULL,
  EPS_NIT_EPS BIGINT NOT NULL,
  PENSION_NIT_PENSION BIGINT NOT NULL,
  CAJA_COMPENSACION_NIT_CAJA BIGINT NOT NULL,
  APORTE_ARL BIGINT,
  APORTE_CAJA BIGINT,
  APORTE_EPS BIGINT,
  APORTE_PENSION BIGINT,
  PRIMARY KEY (SEGURIDAD_SOCIAL_ID)
